/* Mixed float/double. Every result is the double form, which is the rule the rest of this
 * package follows: a double operand widens the whole operation, and nothing is ever rounded
 * down. The same reasoning as the quaternion header, and the same consequence: a device
 * without fp64 cannot compile these, which is correct, because the host cannot do either. */

